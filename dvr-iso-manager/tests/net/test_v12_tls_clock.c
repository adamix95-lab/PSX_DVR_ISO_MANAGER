#include "v12_tls_clock.h"
#include <assert.h>
#include <stdio.h>

static void reject(unsigned status,unsigned yy,unsigned mo,unsigned d,
                   unsigned h,unsigned mi,unsigned s) {
  v12_tls_clock out={1999,11,9,8,7,6};
  assert(v12_tls_clock_decode(status,yy,mo,d,h,mi,s,&out)<0);
  assert(out.year==1999 && out.month==11);
}

int main(void) {
  v12_tls_clock t;
  assert(v12_tls_clock_decode(0,0x26,0x11,0x08,0x23,0x19,0x59,&t)==0);
  assert(t.year==2026 && t.month==11 && t.day==8 && t.hour==23);
  assert(v12_tls_clock_decode(0,0x28,0x82,0x29,0x12,0x00,0x00,&t)==0);
  assert(t.year==2028 && t.month==2 && t.day==29);
  reject(1,0x26,0x11,0x08,0x23,0x19,0x59); /* Stopped RTC */
  reject(2,0x26,0x11,0x08,0x23,0x19,0x59); /* Battery status */
  reject(0,0x24,0x11,0x08,0x23,0x19,0x59); /* Too old */
  reject(0,0x38,0x11,0x08,0x23,0x19,0x59); /* 2038 unsafe */
  reject(0,0x26,0x13,0x08,0x23,0x19,0x59);
  reject(0,0x26,0x11,0x31,0x23,0x19,0x59);
  reject(0,0x26,0x12,0x00,0x23,0x19,0x59);
  reject(0,0x26,0x11,0x08,0x24,0x19,0x59);
  reject(0,0x26,0x11,0x08,0x23,0x60,0x59);
  reject(0,0x26,0x11,0x08,0x23,0x19,0x60);
  reject(0,0x26,0x1a,0x08,0x23,0x19,0x59);
  reject(0,0x26,0x02,0x29,0x23,0x19,0x59);
  reject(0,0x25,0x02,0x29,0x23,0x19,0x59);
  puts("PASS: PS2 BCD RTC sanity checks and fail-closed time policy");
  return 0;
}
